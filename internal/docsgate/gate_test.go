// Package docsgate holds two published descriptions of the code to the code:
// the exported Go API to its checked-in baseline, and the schema's strategy
// enums to the strategies the code takes. Each is verified by breaking it; a
// gate never seen to fail has not been shown to hold.
//
// What it used to hold besides has moved beside what it holds. The readings
// document is lifted by rules, so an erratum with no entry fails the lift;
// the stamping predicates and the choice-point checks read the goldens in
// chargen's tests, beside the roster that generates them; and the coverage
// map is generated by internal/coverage.
//
// The package has no non-test code on purpose.
package docsgate_test

import (
	"os"
	"path/filepath"
	"slices"
	"testing"
)

// docs is where the governing documents live, relative to this package.
const docs = "../../docs"

func read(t *testing.T, name string) string {
	t.Helper()

	text, err := os.ReadFile(filepath.Join(docs, name))
	if err != nil {
		t.Fatalf("the gate cannot read the document it guards: %v", err)
	}

	if len(text) == 0 {
		t.Fatalf("%s is empty", name)
	}

	return string(text)
}

// compare reports every disagreement between two sets, not only the first.
func compare(t *testing.T, inCode, inDoc []string, code, doc string) {
	t.Helper()

	for _, name := range inCode {
		if !slices.Contains(inDoc, name) {
			t.Errorf("%s is in %s but has no entry in %s", name, code, doc)
		}
	}

	for _, name := range inDoc {
		if !slices.Contains(inCode, name) {
			t.Errorf("%s is in %s but does not exist in %s", name, doc, code)
		}
	}
}
